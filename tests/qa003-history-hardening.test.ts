import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { PGlite } from '@electric-sql/pglite';

const root = join(__dirname, '..');
const sql = (name: string) => readFileSync(join(root, 'supabase/drafts/qa003-history-hardening', name), 'utf8');
const migration = (name: string) => readFileSync(join(root, 'supabase/migrations', name), 'utf8');

// Disposable in-process Postgres only: no URL, credentials or Production fixture.
async function fixture() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create table employees(id bigint primary key, role text, is_active boolean default true, status text default 'ACTIVE');
    create table projects(id bigint primary key, status text);
    create table phases(id bigint primary key, project_id bigint references projects(id) on delete cascade, order_index int);
    create table tasks(id bigint generated by default as identity primary key, project_id bigint references projects(id), phase_id bigint,
      parent_task_id bigint, title text, description text, assignee_employee_id bigint, deadline timestamptz, status text,
      created_by_employee_id bigint, updated_by_employee_id bigint, assigned_by_employee_id bigint, assigned_at timestamptz, updated_at timestamptz);
    create table project_members(project_id bigint, employee_id bigint, status text, role_code text);
    create table employee_workspace_access(employee_id bigint, workspace text, status text, revoked_at timestamptz);
    create table employee_permissions(employee_id bigint, permission_code text, effect text, status text, revoked_at timestamptz);
    create table task_comments(id bigint generated by default as identity primary key,
      project_id bigint references projects(id) on delete cascade, task_id bigint references tasks(id) on delete cascade,
      employee_id bigint references employees(id) on delete set null, body text check(length(btrim(body))>0));
    create table project_activity(id bigint generated by default as identity primary key,
      project_id bigint references projects(id) on delete cascade, task_id bigint references tasks(id) on delete set null,
      actor_employee_id bigint references employees(id) on delete set null, activity_type text, payload jsonb,
      constraint project_activity_activity_type_check check(activity_type in
        ('TASK_CREATED','TASK_UPDATED','TASK_ASSIGNED','STATUS_CHANGED','COMMENT_ADDED','PROJECT_CREATED',
         'PRODUCTION_ORDER_CREATED','PRODUCTION_STAGE_ACTIVATED','PRODUCTION_STAGE_COMPLETED','PRODUCTION_STAGE_OVERRIDDEN')));
    create table task_notifications(project_id bigint, task_id bigint, recipient_employee_id bigint, notification_type text, payload jsonb);
    create function can_view_project(bigint) returns boolean language sql stable as
      $$ select $1::text = current_setting('qa003.project',true) $$;
    insert into employees values(1,'OWNER',true,'ACTIVE'),(2,'STAFF',true,'ACTIVE'),(3,'STAFF',true,'ACTIVE'),(4,'STAFF',false,'INACTIVE');
    insert into projects values(1,'ACTIVE'),(2,'ACTIVE'),(3,'CANCELLED');
    insert into phases values(1,1,0),(2,2,0);
    insert into tasks(project_id,title) values(1,'Existing'),(2,'Other project');
    insert into project_members values(1,2,'ACTIVE','CONTRIBUTOR'),(1,3,'ACTIVE','CONTRIBUTOR'),(1,4,'ACTIVE','CONTRIBUTOR');
    alter table task_comments enable row level security;
    alter table project_activity enable row level security;
    create policy comment_read on task_comments for select to authenticated using(can_view_project(project_id));
    create policy activity_read on project_activity for select to authenticated using(can_view_project(project_id));
    grant all on all tables in schema public to service_role;
    grant all on task_comments,project_activity to anon,authenticated;
    grant all on all sequences in schema public to anon,authenticated,service_role;
  `);
  await db.exec(migration('20260727044729_phase_status_dependency.sql'));
  await db.exec(migration('20260815165046_task_assignment_atomic_create.sql'));
  await db.exec(`
    grant all on phase_status_history to service_role;
    grant all on sequence phase_status_history_id_seq to anon,authenticated,service_role;
    insert into task_comments(project_id,task_id,employee_id,body) values(1,1,1,'Existing comment'),(2,2,1,'Other project');
    insert into project_activity(project_id,task_id,actor_employee_id,activity_type,payload)
      values(1,1,1,'PROJECT_CREATED','{}'),(2,2,1,'PRODUCTION_ORDER_CREATED','{}');
    insert into phase_status_history(project_id,phase_id,actor_employee_id,action,new_status,reason)
      values(1,1,1,'UNLOCK','ACTIVE','Fixture'),(2,2,1,'UNLOCK','ACTIVE','Fixture');
  `);
  return db;
}

describe('QA-003 executable history hardening package', () => {
  let db: PGlite;
  const rows = async (query: string) => (await db.query(query)).rows;
  const counts = async () => rows(`select
    (select count(*)::int from tasks) as tasks,
    (select count(*)::int from task_comments) as comments,
    (select count(*)::int from project_activity) as activity,
    (select count(*)::int from task_notifications) as notifications`);
  async function denied(query: string, message: RegExp) {
    await db.exec('savepoint expected_denial');
    await expect(db.exec(query)).rejects.toThrow(message);
    await db.exec('rollback to savepoint expected_denial; release savepoint expected_denial');
  }
  const createTask = (actor=1, phase='1', parent='null', assignee='2', comment="'Hello'") =>
    `select create_project_task_atomic(1,${phase},${parent},'New task',null,${assignee},null,${comment},${actor})`;

  beforeAll(async () => {
    db = await fixture();
    const before = await counts();
    const definitions = () => rows("select oid::regprocedure::text as name, pg_get_functiondef(oid) as source from pg_proc where proname in ('create_project_task_atomic','transition_project_phase_status') order by name");
    const originalFunctions = await definitions();
    await db.exec(sql('forward.sql'));
    expect(await counts()).toEqual(before);
    expect(await definitions()).toEqual(originalFunctions);
    await db.exec(sql('validation.sql'));
  }, 30000);
  beforeEach(async () => { await db.exec('begin'); });
  afterEach(async () => { await db.exec('rollback; reset role'); });
  afterAll(async () => { await db?.close(); });

  it('keeps task/comment/activity/notification writes atomic for an authorized actor', async () => {
    await db.exec('set local role service_role');
    await db.exec(createTask());
    expect(await counts()).toEqual([{ tasks:3, comments:3, activity:3, notifications:1 }]);
  });

  it('supports the required legacy task columns on Production and restores the original function on rollback', async () => {
    const compat = (name: string) => readFileSync(join(root, 'supabase/drafts/task-assignment-create-compatibility', name), 'utf8');
    const isolated = await fixture();
    try {
      await isolated.exec(`
        alter table projects add column project_name text not null default 'Project fixture';
        alter table tasks add column project_name text not null default 'Existing';
        alter table tasks add column assigned_to text not null default '';
        alter table tasks add column current_phase text;
        alter table tasks alter column project_name drop default;
        alter table tasks alter column assigned_to drop default;
      `);
      const original = await isolated.query("select prosrc from pg_proc where proname='create_project_task_atomic'");
      await expect(isolated.exec(createTask())).rejects.toThrow(/project_name/);
      await isolated.exec(compat('forward.sql'));
      await isolated.exec('set role service_role');
      await isolated.exec(createTask());
      expect((await isolated.query("select project_name, assigned_to, current_phase from tasks where title='New task'")).rows)
        .toEqual([{ project_name: 'Project fixture', assigned_to: '', current_phase: 'IN_PROG' }]);
      await isolated.exec('reset role');
      expect((await isolated.query(compat('validation.sql'))).rows[0]).toMatchObject({
        prosecdef: false, service_role_execute: true, authenticated_execute: false,
        anon_execute: false, legacy_columns_supported: true,
      });
      await isolated.exec(compat('rollback.sql'));
      expect((await isolated.query("select prosrc from pg_proc where proname='create_project_task_atomic'")).rows).toEqual(original.rows);
    } finally {
      await isolated.close();
    }
  }, 15000);

  it.each([
    { name:'contributor', query:createTask(3), message:/permission_forbidden/ },
    { name:'inactive assignee', query:createTask(1,'1','null','4'), message:/assignee_invalid/ },
    { name:'cross-project phase', query:createTask(1,'2'), message:/phase_invalid/ },
    { name:'cross-project parent', query:createTask(1,'1','2'), message:/parent_invalid/ },
  ])('rejects $name without partial rows', async ({ query, message }) => {
    const before = await counts();
    await db.exec('set local role service_role');
    await denied(query, message);
    expect(await counts()).toEqual(before);
  });

  it('rejects a cancelled project without partial rows', async () => {
    const before = await counts();
    await db.exec('set local role service_role');
    await denied("select create_project_task_atomic(3,null,null,'Closed',null,null,null,null,1)", /project_closed/);
    expect(await counts()).toEqual(before);
  });

  it.each(['task_comments','project_activity','task_notifications'])('rolls back the whole create when %s fails', async (table) => {
    const before = await counts();
    await db.exec(`alter table ${table} add constraint forced_failure check(false) not valid; set local role service_role`);
    await denied(createTask(), /forced_failure/);
    expect(await counts()).toEqual(before);
  });

  it.each(['anon','authenticated'])('denies %s mutations and sequence access', async (role) => {
    await db.exec(`set local role ${role}; set local qa003.project='1'`);
    for (const table of ['task_comments','project_activity','phase_status_history']) {
      for (const query of [`insert into ${table} default values`,`update ${table} set id=id`,`delete from ${table}`,`truncate ${table}`]) {
        await denied(query,/permission denied/);
      }
      await denied(`select nextval('${table}_id_seq')`,/permission denied/);
      await denied(`select setval('${table}_id_seq',1000)`,/permission denied/);
      if (role==='anon') await denied(`select * from ${table}`,/permission denied/);
      else expect((await rows(`select project_id from ${table}`))).toEqual([{project_id:1}]);
    }
  });

  it('blocks update/delete/truncate even for the table owner, including FK cascades', async () => {
    for (const table of ['task_comments','project_activity','phase_status_history']) {
      for (const query of [`update ${table} set id=id`,`delete from ${table}`,`truncate ${table}`]) {
        await denied(query,/history is immutable/);
      }
    }
    await denied('delete from projects where id=1',/history is immutable|foreign key/);
    await denied('delete from tasks where id=1',/history is immutable/);
    await denied('delete from employees where id=1',/history is immutable|foreign key/);
    expect(await rows('select count(*)::int as n from projects')).toEqual([{n:3}]);
  });

  it('retains phase transition and rejects stale concurrent state', async () => {
    await db.exec('set local role service_role');
    await db.exec("select transition_project_phase_status(1,1,1,'COMPLETE','ACTIVE','COMPLETED','Done')");
    await denied("select transition_project_phase_status(1,1,1,'COMPLETE','ACTIVE','COMPLETED','Duplicate')",/concurrently/);
    expect(await rows('select status from phases where id=1')).toEqual([{status:'COMPLETED'}]);
    expect(await rows('select count(*)::int as n from phase_status_history')).toEqual([{n:3}]);
    await denied("select setval('phase_status_history_id_seq',1000)",/permission denied/);
  });

  it('does not overwrite the current PROJECT_CREATED/production event check', async () => {
    const results = await db.query<{definition:string}>("select pg_get_constraintdef(oid) as definition from pg_constraint where conname='project_activity_activity_type_check'");
    expect(results.rows[0].definition).toContain('PROJECT_CREATED');
    expect(results.rows[0].definition).toContain('PRODUCTION_STAGE_OVERRIDDEN');
    await denied(sql('forward.sql'),/already exists/);
  });

  it('fails closed on read-policy drift before changing grants or installing triggers', async () => {
    const drift = await fixture();
    try {
      await drift.exec('alter table project_activity disable row level security');
      await expect(drift.exec(sql('forward.sql'))).rejects.toThrow(/QA003 drift/);
      await drift.exec('rollback');
      expect((await drift.query<{found:string|null}>("select to_regprocedure('public.reject_project_history_mutation()')::text as found")).rows[0].found).toBeNull();
      expect((await drift.query<{allowed:boolean}>("select has_table_privilege('anon','project_activity','TRUNCATE') as allowed")).rows[0].allowed).toBe(true);
    } finally { await drift.close(); }
  },30000);

  it('rollback preserves all history and tightened browser grants', async () => {
    const rollback = await fixture();
    try {
      await rollback.exec(sql('forward.sql'));
      await rollback.exec(sql('rollback.sql'));
      expect((await rollback.query<{n:number}>('select count(*)::int as n from project_activity')).rows).toEqual([{n:2}]);
      expect((await rollback.query<{allowed:boolean}>("select has_table_privilege('anon','project_activity','TRUNCATE') as allowed")).rows[0].allowed).toBe(false);
      expect((await rollback.query<{allowed:boolean}>("select has_table_privilege('service_role','project_activity','UPDATE') as allowed")).rows[0].allowed).toBe(false);
    } finally { await rollback.close(); }
  },30000);
});
