  constraint phase_templates_project_type_check check (project_type = 'GENERAL'),
  constraint phase_templates_status_check check (status in ('ACTIVE', 'ARCHIVED')),
  constraint phase_templates_normalized_name_unique unique (project_type, normalized_name)
);

create table public.phase_template_versions (
  id bigint generated by default as identity primary key,
  template_id bigint not null references public.phase_templates(id) on delete restrict,
  version_number integer not null,
  status text not null default 'DRAFT',
  source_version_id bigint null references public.phase_template_versions(id) on delete restrict,
  published_at timestamptz null,
  archived_at timestamptz null,
  created_by_employee_id bigint not null references public.employees(id) on delete restrict,
  updated_by_employee_id bigint not null references public.employees(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint phase_template_versions_number_positive check (version_number > 0),
  constraint phase_template_versions_status_check check (status in ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
  constraint phase_template_versions_lifecycle_check check (
    (status = 'DRAFT' and published_at is null and archived_at is null)
    or (status = 'PUBLISHED' and published_at is not null and archived_at is null)
    or (status = 'ARCHIVED' and archived_at is not null)
  ),
  constraint phase_template_versions_template_number_unique unique (template_id, version_number)
);

