create policy phase_template_versions_authorized_read on public.phase_template_versions for select to authenticated using (
  public.has_workspace_access('ADMIN_WORKSPACE') and (
    public.has_permission('PHASE_TEMPLATE_MANAGE')
    or (status = 'PUBLISHED' and public.has_permission('PROJECT_MANAGE') and exists (
      select 1 from public.phase_templates template
      where template.id = phase_template_versions.template_id
        and template.status = 'ACTIVE'
        and template.current_version_id = phase_template_versions.id
    ))
  )
);
