create function public.phase_template_reject_immutable_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'phase_template_immutable_row' using errcode = 'P0001';
end;
$$;

create function public.phase_template_protect_audit_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE'
    and old.version_id is not null and new.version_id is null
    and new.id = old.id
    and new.template_id is not distinct from old.template_id
    and new.actor_employee_id = old.actor_employee_id
    and new.action = old.action
    and new.reason is not distinct from old.reason
    and new.before_data is not distinct from old.before_data
    and new.after_data is not distinct from old.after_data
    and new.occurred_at = old.occurred_at
    and new.retain_until = old.retain_until then
    return new;
  end if;
  raise exception 'phase_template_audit_immutable_row' using errcode = 'P0001';
end;
$$;

create function public.phase_template_validate_current_version()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.current_version_id is not null and not exists (
    select 1
    from public.phase_template_versions version
    where version.id = new.current_version_id
      and version.template_id = new.id
      and version.status = 'PUBLISHED'
  ) then
    raise exception 'phase_template_current_version_invalid' using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger phase_templates_current_version_guard
before insert or update of current_version_id on public.phase_templates
for each row execute function public.phase_template_validate_current_version();

create trigger phase_template_applications_immutable
