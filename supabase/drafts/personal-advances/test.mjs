import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const forward = await readFile(new URL('forward.sql', import.meta.url), 'utf8');
const rollback = await readFile(new URL('rollback.sql', import.meta.url), 'utf8');
const fixture = `
create role anon; create role authenticated; create role service_role bypassrls;
create table employees(id bigint primary key);
create table shareholders(id bigint primary key, name text, status text);
create table financial_ledger(
  id bigint generated by default as identity primary key, type text, sub_type text, category text, amount numeric,
  month_period text, transaction_date date, requested_by text, is_paid boolean, payment_status text,
  creator_employee_id bigint references employees, payment_confirmer_employee_id bigint references employees,
  source_type text, source_reference text, beneficiary_external_name text, updated_at timestamptz,
  cancelled_at timestamptz, paid_at timestamptz, unique(source_type, source_reference)
);
create table payroll_ledger_links(ledger_id bigint, state text);
create table payroll_supplemental_obligations(ledger_id bigint);
create table erp_activity_events(actor_employee_id bigint, entity text, entity_id bigint, action text, screen text, summary text, changes_text text);
create table notices(ledger_id bigint unique);
create function confirm_salary_ledger_payment(bigint,date,bigint) returns uuid language plpgsql as $$
begin
  update public.financial_ledger set is_paid = true, payment_status = 'PAID' where id = $1;
  insert into public.notices values ($1);
  return gen_random_uuid();
end $$;
insert into employees values (1);
insert into shareholders values (7,'Hà','ACTIVE'), (8,'Duy','ACTIVE');
insert into financial_ledger(type,category,amount,month_period,is_paid,source_type) values
  ('CHI_PHI','Lương',2160000,'11/2026',false,'PAYROLL'),
  ('CHI_PHI','Lương bổ sung',100,'11/2026',false,'PAYROLL_SUPPLEMENT');
insert into payroll_ledger_links values (1,'ACTIVE');
insert into payroll_supplemental_obligations values (2);
grant select, update on financial_ledger to service_role;
grant select on shareholders to service_role;
`;
const get = async sql => (await db.query(sql)).rows[0];
const refund = (amount, id) => db.query(`select record_personal_advance_refund(1,${amount},1,'00000000-0000-0000-0000-00000000000${id}') id`);
try {
  await db.exec(fixture);
  await db.exec(forward);
  await db.exec(rollback);
  await db.exec(forward);
  await db.exec('set role authenticated');
  await assert.rejects(db.query('select record_payroll_personal_advance(1,7,1)'), /permission denied/);
  await db.exec('reset role; set role service_role');
  await assert.rejects(db.query("select confirm_payroll_payment_with_source(1,'2026-10-01',1,99)"), /advance_shareholder_invalid/);
  assert.equal((await get('select is_paid from financial_ledger where id=1')).is_paid, false);
  await db.query("select confirm_payroll_payment_with_source(1,'2026-10-01',1,7)");
  await assert.rejects(db.query("select confirm_payroll_payment_with_source(1,'2026-10-01',1,7)"), /payment_already_recorded/);
  await db.query('select record_payroll_personal_advance(1,8,1)');
  await db.query('select record_payroll_personal_advance(1,null,1)');
  await db.query('select record_payroll_personal_advance(1,7,1)');
  assert.equal((await get("select count(*)::int n from financial_ledger where source_type='PERSONAL_ADVANCE' and cancelled_at is null")).n, 1);
  const first = await refund(1000000, 1);
  assert.deepEqual((await refund(1000000, 1)).rows, first.rows);
  await assert.rejects(refund(2000000, 2), /refund_exceeds_outstanding/);
  await assert.rejects(db.query('select record_payroll_personal_advance(1,null,1)'), /advance_already_refunded/);
  await assert.rejects(db.query("update financial_ledger set amount=1 where source_type='PERSONAL_ADVANCE_REFUND'"), /advance_ledger_protected/);
  await refund(1160000, 2);
  const { entry: summary } = await get('select list_personal_advances()->0 as entry');
  assert.equal(summary.person, 'Hà');
  assert.equal(Number(summary.advanced), 2160000);
  assert.equal(Number(summary.refunded), 2160000);
  await db.exec('reset role');
  assert.equal((await get('select count(*)::int n from notices')).n, 1);
  await assert.rejects(db.exec(rollback), /advance_history_exists_keep_schema/);
  console.log('PASS source correction, atomic payment, browser ACL, two refunds, replay, overpayment, immutable rows and rollback boundary');
} finally {
  await db.close();
}
