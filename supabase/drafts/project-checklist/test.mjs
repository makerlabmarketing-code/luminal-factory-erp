async function verifyConcurrentUpdates(db, taskId, state) {
  const [first, second] = db.clients;
  const [{ rows: [winner] }, { rows: [contender] }] = await Promise.all([
    first.query('select pg_backend_pid() as pid'),
    second.query('select pg_backend_pid() as pid'),
  ]);
  assert.notEqual(winner.pid, contender.pid);

  const update = (client, expected, next, note, deadline, changeDeadline = false) => client.query(
    'select update_staff_checklist_task($1, 2, $2, $3, $4, $5, $6) as result',
    [taskId, expected, next, note, deadline, changeDeadline],
  ).then(({ rows: [row] }) => row.result);

  async function whileLocked(hold, contend) {
    await first.query('begin');
    let pending;
    try {
      await hold();
      pending = contend();
      pending.catch(() => {});
      let waitedForWinner = false;
      for (let attempt = 0; attempt < 40; attempt++) {
        const { rows: [row] } = await db.query(
          'select $1::int = any(pg_blocking_pids($2::int)) as waiting',
          [winner.pid, contender.pid],
        );
        if (row.waiting) {
          waitedForWinner = true;
          break;
        }
        await delay(75);
      }
      assert.ok(waitedForWinner, 'The second connection must wait for the first transaction');
      await first.query('commit');
      return await pending;
    } finally {
      await first.query('rollback');
      await pending?.catch(() => {});
    }
  }

  await db.query("update tasks set status='READY', deadline='2026-10-24T00:00:00Z' where id=$1", [taskId]);
  const before = await state();
  const rejected = await whileLocked(
    async () => assert.equal((await update(first, 'READY', 'IN_PROGRESS', 'First note', null)).success, true),
    () => update(second, 'READY', 'IN_PROGRESS', 'Stale note', '2026-10-29T00:00:00Z', true),
  );
  assert.equal(rejected.code, 'stale_task');
  assert.deepEqual(await state(), {
    ...before, status: 'IN_PROGRESS', comments: before.comments + 1, activity: before.activity + 1,
  });

  const submitted = await whileLocked(
    () => first.query("update tasks set deadline='2026-10-28T00:00:00Z' where id=$1", [taskId]),
    () => update(second, 'IN_PROGRESS', 'PENDING_REVIEW', null, '2026-10-24T00:00:00Z'),
  );
  assert.equal(submitted.success, true);
  assert.equal((await state()).deadline, '2026-10-28');
  assert.equal((await state()).status, 'PENDING_REVIEW');
  console.log('PASS: 2 overlapping checklist updates with observed PostgreSQL lock waits');
}

